#!/usr/bin/env python3
"""Generate OsuProofs/Auto/Res.lean: for every ∃-form refinement theorem (hand-written in the Manual layer or
generated in Auto/Gen.lean)
    theorem X_refines (bs) : ∃ r, f xs = ok r ∧ P r
emit a result function and two lemmas, so that `simp` can evaluate Rust code calling `f`:
    theorem X_ok (bs) : f xs = ok (X_refines xs).choose
    @[simp] theorem X_R_abs (bs) : abs (X_refines xs).choose = LHS   (when P r is `LHS = abs r`; else X_R_spec)
(statements via `type_of%`, so they need no re-elaboration in the original file's context)
usage: gen_res.py > OsuProofs/Auto/Res.lean"""
import os, re, glob, sys
sys.path.insert(0, os.path.dirname(__file__))
from gen_steps import split_top, binders_of
P = os.path.expanduser('~/lazerproof/proofs')
files = sorted(glob.glob(P + '/OsuProofs/**/*.lean', recursive=True))
manual = open(P + '/OsuProofs/Manual.lean').read()
out = ['/- GENERATED by scripts/gen_res.py: choose-equations of the ∃-form refinement theorems (see there). -/',
       'import OsuProofs.Auto.Gen', 'set_option linter.all false', 'open Aeneas Aeneas.Std Result',
       'open OsuModel.Net OsuModel.Beatmap', '', 'namespace OsuProofs', 'open OsuImpl', '']
seen = set()
for f in files:
    if '/Generated/' in f or '/Post/' in f or f.endswith('/Res.lean') or f.endswith('/Schedule.lean'): continue
    mod = f[len(P) + 1:-5].replace('/', '.')
    if '/Auto/' not in f and f'import {mod}\n' not in manual + '\n': continue
    txt = open(f).read()
    for m in re.finditer(r'^theorem ([\w.]+)_refines (.*?):= ?(?:by)?\s*$', txt, re.M | re.S):
        name, head = m.group(1), m.group(2)
        if '\ntheorem ' in head or '\n\n' in head or name in seen: continue
        parts = split_top(head, ' :')
        if len(parts) < 2: continue
        bs, concl = ' :'.join(parts[:-1]), ' '.join(parts[-1].split())
        b = binders_of(bs)
        if b is None or any(e != '(' for _, _, e in b): continue
        me = re.fullmatch(r'∃ (\w+), (.+?) = ok \1 ∧ (.+)', concl)
        if not me: continue
        r, lhs, post = me.groups()
        if re.search(r'∃|∀', post): continue
        args = ' '.join(n for ns, _, _ in b for n in ns)
        seen.add(name)
        bs = ' '.join(bs.split())
        pf = f'({name}_refines {args})'
        # statements are inferred (`type_of%`): no re-elaboration of the original file's notation/opens
        out.append(f'theorem {name}_ok {bs} : type_of% {pf}.choose_spec.1 := {pf}.choose_spec.1')
        if re.fullmatch(r'(.+) = abs ' + r, post):
            out.append(f'@[simp] theorem {name}_R_abs {bs} : type_of% {pf}.choose_spec.2.symm := {pf}.choose_spec.2.symm')
        else:
            out.append(f'theorem {name}_R_spec {bs} : type_of% {pf}.choose_spec.2 := {pf}.choose_spec.2')
        out.append('')
out.append('end OsuProofs')
print('\n'.join(out))
