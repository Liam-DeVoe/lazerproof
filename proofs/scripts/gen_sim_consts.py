#!/usr/bin/env python3
"""Generate `@[simp]` lemmas `float.F64.from_bits N#u64 = ok (lit : F64)` (and F32) for every float bit-pattern
literal in Generated/SimFuns.lean (shortest round-trip decimal; the Lean literal is correctly rounded to the same
bits). Output: OsuProofs/Sim/Consts.lean (each lemma by `decide`)."""
import os, re, struct
P = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
src = open(os.path.join(P, 'OsuProofs/Generated/SimFuns.lean')).read()
def short32(b):
    x = struct.unpack('<f', struct.pack('<I', b))[0]
    for d in range(1, 18):
        s = '%.*g' % (d, x)
        if struct.unpack('<I', struct.pack('<f', float(s)))[0] == b: return s
def lit(s):
    s = s.replace('e+', 'e')
    if s.endswith('.0') and 'e' not in s: return s[:-2]  # integral: the spec writes `5`, `500000`
    if 'e' not in s and '.' not in s: s += '.0'
    neg = s.startswith('-'); s = s.lstrip('-')
    return ('-' if neg else '') + s
out = ['/- Generated by proofs/scripts/gen_sim_consts.py. Do not edit. -/', 'import OsuProofs.Sim.Abs',
       'open Aeneas Aeneas.Std Result', 'namespace OsuProofs', 'open OsuImpl', '']
for n in sorted(set(int(m) for m in re.findall(r'float\.F64\.from_bits (\d+)#u64', src))):
    x = struct.unpack('<d', struct.pack('<Q', n))[0]
    if x != x or x in (float('inf'), float('-inf')) or (x == 0 and n != 0) or (x != 0 and abs(x) < 2.3e-308) or abs(x) > 1e30: continue
    out.append(f'@[simp high] theorem fb64_{n} : float.F64.from_bits {n}#u64 = ok ({lit(repr(x))} : OsuModel.Net.F64) := by\n  simp [float.F64.from_bits]; decide')
    out.append(f'@[simp] theorem ob64_{n} : Float.ofBits {n} = ({lit(repr(x))} : OsuModel.Net.F64) := by decide')
for n in sorted(set(int(m) for m in re.findall(r'float\.F32\.from_bits (\d+)#u32', src))):
    x = struct.unpack('<f', struct.pack('<I', n))[0]
    if x != x or x in (float('inf'), float('-inf')) or (x == 0 and n != 0) or (x != 0 and abs(x) < 1.2e-38) or abs(x) > 1e30: continue
    out.append(f'@[simp high] theorem fb32_{n} : float.F32.from_bits {n}#u32 = ok ({lit(short32(n))} : OsuModel.Net.F32) := by\n  simp [float.F32.from_bits]; decide')
    out.append(f'@[simp] theorem ob32_{n} : Float32.ofBits {n} = ({lit(short32(n))} : OsuModel.Net.F32) := by decide')
out.append('\nend OsuProofs')
open(os.path.join(P, 'OsuProofs/Sim/Consts.lean'), 'w').write('\n'.join(out) + '\n')
print(len(out) - 7, 'lemmas')
